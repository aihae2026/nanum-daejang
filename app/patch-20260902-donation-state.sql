-- 나눔대장 — 패치 2026-09-02: donation.state 에 '제출 대기' · '취소' 추가
--   drop 없음(제약만 교체) · 여러 번 실행해도 안전 · 기존 데이터 유지
--
-- 왜 필요한가 (유진 · 새 접수 저장 붙이다 발견)
--   화면은 다섯 상태를 쓰는데 DB 제약은 셋만 받는다.
--     화면: 제출 대기 · 접수 검토 · 검수 대기 · 완결 · 취소
--     DB  : 접수 검토 · 검수 대기 · 완결
--   그래서 **새 접수를 넣는 순간 거부당한다.** 접수 생성이 DB 에 안 남던 이유다.
--
--   '제출 대기' 는 진짜 업무 상태다 — 링크를 발급했고 후원자가 아직 안 낸 구간.
--   '취소' 도 마찬가지다(오발송 대비 · 사유 보존). 화면이 지어낸 값이 아니라
--   스키마에 빠져 있던 것이다.
--
-- 어느 쪽에 맞췄나 — **코드에 맞춰 DB 를 넓혔다.**
--   8/31 doc_key 때와 같은 판단이다(선미·유진 (가)안).
--   화면 코드는 여러 곳에서 이 값으로 분기하고, DB 는 더미 4건뿐이라 고치는 비용이 작다.
--
-- ⚠️ 이 패치를 실행하지 않으면
--   새 접수 insert 가 조용히 실패한다 — 화면에는 접수가 뜨는데 DB 에는 없다.
--   코드가 실패를 화면에 세우도록 만들어 뒀지만(담당자가 볼 수 있게),
--   그래도 접수는 저장되지 않는다.
--
-- 실행: Supabase SQL Editor 에 붙여넣고 Run · 30초
-- ============================================================================

alter table donation drop constraint if exists donation_state_check;

alter table donation add constraint donation_state_check
  check (state in ('제출 대기', '접수 검토', '검수 대기', '완결', '취소'));

comment on column donation.state is
  '건 상태 — 제출 대기(링크 발급 · 후원자 미제출) → 접수 검토 → 검수 대기 → 완결. '
  '취소는 오발송 대비(사유 보존). 화면 표기와 같은 값을 쓴다(표기가 갈리면 통계가 섞인다).';

-- 확인
select conname, pg_get_constraintdef(oid)
from pg_constraint
where conrelid = 'donation'::regclass and conname = 'donation_state_check';
