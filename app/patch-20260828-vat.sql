-- 나눔대장 — 패치 2026-08-28: 매입세액공제 여부 컬럼 추가
--   drop 없음 · 여러 번 실행해도 안전(if not exists) · 기존 데이터 유지
--
-- 왜 필요한가 (유진 발견 · 선미 결정 "정석대로")
--   기관 업무지침: 매입세액공제를 받는 후원처의 물품은 공제가 겹치지 않도록
--   부가세를 뺀 공급가액으로 기부금영수증을 발급한다 (요지)
--
--   즉 금액 신고 기준이 두 갈래다:
--     · 매입세액공제 받음   → 공급가액(부가세 제외)으로 신고
--     · 받지 않음/모름      → 합계로 신고
--
--   이 컬럼이 없으면 E1(금액 대조)이 무엇과 비교할지 알 수 없어
--   공제받는 법인은 전건 오탐이 난다 (T02 기준 113,619원 차이).
--
--   ※ 면세사업자 여부(예외②)와는 다른 항목이다. 둘 다 필요하다.
-- ============================================================================

alter table donation
  add column if not exists vat_deduction text
    check (vat_deduction in ('예', '아니오', '모름'));

comment on column donation.vat_deduction is
  '매입세액공제 여부 (기관 업무지침). E1이 서류의 공급가액과 합계 중 무엇과 대조할지를 가른다. '
  '''예''=공급가액 기준 · ''아니오''=합계 기준 · ''모름''/NULL=둘 다 읽어 어느 쪽과 맞는지 사유에 적고 '
  '담당자에게 넘긴다(자동 통과 없음, inspection-rubric.md 2-E1). 면세사업자 여부와는 별개 항목.';

-- ★ NULL(미입력)은 '모름'과 같게 취급한다 — '아니오'가 아니다.
--   '모름'이면 코드가 서류의 합계·공급가액을 둘 다 보고 어느 쪽과 맞는지를 사유에 적어
--   담당자에게 넘긴다 (자동 통과시키지 않는다). 규칙 전문은 inspection-rubric.md §2-E1.
--   담당자가 후원자에게 확인해 값을 확정하면 그 뒤부터 자동 판정된다.
-- 화면·폼이 붙은 뒤에는 접수 시점에 채운다.

-- 확인
select case_no, donor_type, vat_deduction, book_value
from donation order by case_no;
